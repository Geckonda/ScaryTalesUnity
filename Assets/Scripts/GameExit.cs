using UnityEngine;

/// <summary>
/// Выход из приложения — одним местом на всю игру.
///
/// <para>Вынесено из кнопок, потому что выходов уже два: меню по Esc и главное
/// меню. Ветка «в редакторе <c>Application.Quit</c> ничего не делает» обязана
/// быть одна: продублированная, она однажды разъедется, и одна из кнопок
/// станет молча ничего не делать — тот самый вид поломки, который списывают
/// на «наверное, так и задумано».</para>
/// </summary>
public static class GameExit
{
    /// <summary>
    /// Закрыть игру.
    ///
    /// <para>Сеть здесь намеренно не трогается. Разрыв соединения и так
    /// случится при закрытии процесса, а сервер обрабатывает уход игрока
    /// одинаково, чем бы тот ни был вызван: освобождает место, завершает
    /// партию и убирает опустевшую комнату (<c>ReleaseConnection</c>).
    /// Отправлять что-либо прямо перед закрытием бессмысленно — оно рискует
    /// не успеть уйти, ровно как в <c>PauseMenu.LeaveRoom</c>.</para>
    /// </summary>
    public static void QuitApplication()
    {
        Debug.Log("[GameExit] Выход из игры.");

#if UNITY_EDITOR
        // В редакторе Application.Quit() не делает ничего, и кнопка выглядит
        // сломанной — проверить её было бы нечем, кроме сборки.
        UnityEditor.EditorApplication.isPlaying = false;
#else
        Application.Quit();
#endif
    }
}
