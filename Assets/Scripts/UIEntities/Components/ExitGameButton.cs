using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Кнопка «Выйти из игры». Повесить на объект кнопки — больше ничего не нужно.
///
/// <para>Компонент сам находит <see cref="Button"/> на своём объекте и
/// подписывается на нажатие, поэтому в сцене не остаётся ни слота, который
/// можно забыть привязать, ни записи в OnClick, которая отвалится при
/// переименовании метода. В этом проекте забытая привязка уже не раз выглядела
/// как «кнопка не работает», причём искать в ней нечего: обработчик просто не
/// подключён.</para>
///
/// <para>Работает где угодно — в главном меню, в меню по Esc, на экране
/// результата: компонент ничего не знает ни о партии, ни о сети.</para>
/// </summary>
[RequireComponent(typeof(Button))]
public class ExitGameButton : MonoBehaviour
{
    private void Awake() => GetComponent<Button>().onClick.AddListener(Quit);

    /// <summary>
    /// Закрыть игру. Public — то же самое можно повесить руками через OnClick
    /// в инспекторе; тогда обработчик сработает дважды, а второй выход уже
    /// ничего не меняет.
    /// </summary>
    public void Quit() => GameExit.QuitApplication();
}
