using System.Collections.Generic;
using System.Linq;

namespace ScaryTales
{
    /// <summary>
    /// Кто победил.
    ///
    /// <para>Живёт в библиотеке движка, а не в серверной комнате, по двум
    /// причинам. Во-первых, это правило игры, а не деталь сети. Во-вторых,
    /// раньше подсчёт был написан прямо в цикле хода как
    /// <c>OrderByDescending(p =&gt; p.Score).First()</c> — и при равном счёте
    /// тихо назначал победителем того, кто раньше сел за стол. Ничья в этой
    /// игре бывает часто, и такую ошибку не видно ниоткуда, кроме как из
    /// теста.</para>
    /// </summary>
    public static class Outcome
    {
        /// <summary>
        /// Id всех, кто набрал наибольший счёт.
        ///
        /// <para>При равенстве побеждают все — партия объявляется ничьей, а не
        /// достаётся первому по списку.</para>
        /// </summary>
        /// <returns>
        /// Id победителей по возрастанию. Пустой массив, если игроков не
        /// осталось (все вышли до конца партии) — это не победа никого по
        /// ошибке, а честное «победителя нет».
        /// </returns>
        public static int[] ComputeWinners(IReadOnlyList<Player> players)
        {
            if (players == null || players.Count == 0) return new int[0];

            int best = players.Max(p => p.Score);

            // Сортировка по Id, а не по порядку мест: список игроков за партию
            // мог перетасоваться (кто-то вышел), и порядок победителей не
            // должен зависеть от того, кто когда отключился.
            return players
                .Where(p => p.Score == best)
                .Select(p => p.Id)
                .OrderBy(id => id)
                .ToArray();
        }
    }
}
